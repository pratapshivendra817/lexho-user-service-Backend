CREATE TABLE IF NOT EXISTS cart_config (
    id BIGINT PRIMARY KEY,
    max_cart_items INT NOT NULL,
    min_service_quantity INT NOT NULL,
    max_service_quantity INT NOT NULL,
    min_cleaning_duration_hours DECIMAL(4,2) NOT NULL,
    max_cleaning_duration_hours DECIMAL(4,2) NOT NULL,
    instant_booking_window_minutes INT NOT NULL,
    scheduled_booking_window_days INT NOT NULL,
    slot_interval_minutes INT NOT NULL,
    instant_booking_enabled BOOLEAN NOT NULL,
    scheduled_booking_enabled BOOLEAN NOT NULL,
    subscription_booking_enabled BOOLEAN NOT NULL,
    require_slot_recheck BOOLEAN NOT NULL,
    reject_full_slots BOOLEAN NOT NULL,
    max_bookings_per_slot INT NOT NULL,
    subscription_checkout_enabled BOOLEAN NOT NULL,
    subscription_payment_required BOOLEAN NOT NULL,
    subscription_auto_renew_enabled BOOLEAN NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    CONSTRAINT chk_cart_config_max_cart_items CHECK (max_cart_items >= 1),
    CONSTRAINT chk_cart_config_min_service_qty CHECK (min_service_quantity >= 1),
    CONSTRAINT chk_cart_config_max_service_qty CHECK (max_service_quantity >= min_service_quantity),
    CONSTRAINT chk_cart_config_min_cleaning_hours CHECK (min_cleaning_duration_hours >= 0.5),
    CONSTRAINT chk_cart_config_max_cleaning_hours CHECK (max_cleaning_duration_hours >= min_cleaning_duration_hours),
    CONSTRAINT chk_cart_config_instant_window CHECK (instant_booking_window_minutes >= 1),
    CONSTRAINT chk_cart_config_scheduled_days CHECK (scheduled_booking_window_days >= 1),
    CONSTRAINT chk_cart_config_slot_interval CHECK (slot_interval_minutes >= 1),
    CONSTRAINT chk_cart_config_max_bookings_slot CHECK (max_bookings_per_slot >= 1)
);

